class BuildError(RuntimeError):
    """A user-facing build failure with an actionable message."""


@dataclass(frozen=True)
class Source:
    directory: Path
    version: str
    tree_hash: str


@dataclass(frozen=True)
class PythonTarget:
    executable: Path
    version: str  # "major.minor", as RL_BUILD_PYTHON_WRAPPER expects
    full_version: str
    include_dir: Path
    library: Path | None  # only needed by FindPython; never linked on macOS/Linux


@dataclass(frozen=True)
class Swig:
    executable: Path
    library_dir: Path  # SWIG_DIR / SWIG_LIB: the directory holding swig.swg

    @property
    def needs_stringify_compat(self) -> bool:
        """True for SWIG >= 4.4, whose runtime no longer defines the macro RigLogic.i uses."""
        runtime = (self.library_dir / "swigrun.swg").read_text(encoding="utf-8", errors="replace")
        return OLD_SWIG_STRINGIFY not in runtime


@dataclass(frozen=True)
class Toolchain:
    cmake: Path
    cmake_version: tuple[int, ...]
    generator: str
    generator_args: tuple[str, ...] = ()
    cmake_args: tuple[str, ...] = ()
    env: dict[str, str] = field(default_factory=dict)
    description: str = ""


# ---------------------------------------------------------------------------- helpers


def log(message: str) -> None:
    print(f"[openriglogic] {message}", flush=True)


def format_command(command: Sequence[str]) -> str:
    if sys.platform == "win32":
        return subprocess.list2cmdline(list(command))
    return shlex.join(command)


def run(
    command: Sequence[str], *, env: dict[str, str] | None = None, cwd: Path | None = None
) -> None:
    log(f"$ {format_command(command)}")
    completed = subprocess.run(list(command), env=env, cwd=cwd, check=False)
    if completed.returncode != 0:
        raise BuildError(f"command failed with exit code {completed.returncode}: {command[0]}")


def capture(command: Sequence[str], *, env: dict[str, str] | None = None) -> str:
    completed = subprocess.run(list(command), env=env, capture_output=True, text=True, check=False)
    if completed.returncode != 0:
        raise BuildError(
            f"command failed ({completed.returncode}): {format_command(command)}\n"
            f"{completed.stderr.strip()}"
        )
    return completed.stdout


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def which(name: str, env: dict[str, str] | None = None) -> Path | None:
    path_value = None
    if env is not None:
        path_value = next((v for k, v in env.items() if k.upper() == "PATH"), None)
    found = shutil.which(name, path=path_value)
    return Path(found) if found else None


def version_tuple(text: str) -> tuple[int, ...]:
    match = re.search(r"(\d+)\.(\d+)(?:\.(\d+))?", text)
    if not match:
        return ()
    return tuple(int(part) for part in match.groups() if part is not None)


