FIXUPS_CMAKE = """\
# Generated by pipeline/scripts/build_openriglogic.py. Do not edit.
function(_ai_sims_fixups)
    foreach(_target IN ITEMS py3dna py3riglogic)
        if(NOT TARGET ${_target})
            message(FATAL_ERROR "Expected target ${_target}; was RL_BUILD_PYTHON_WRAPPER set?")
        endif()
    endforeach()
    # RigLogic.i patches SWIG_GetModule with SWIG_EXPAND_AND_QUOTE_STRING, which SWIG 4.4
    # renamed to SWIG_STRINGIFY. A forced include restores the old spelling.
    if(AI_SIMS_SWIG_COMPAT_HEADER)
        if(MSVC)
            target_compile_options(py3riglogic PRIVATE "/FI${AI_SIMS_SWIG_COMPAT_HEADER}")
        else()
            target_compile_options(py3riglogic PRIVATE
                "SHELL:-include \\"${AI_SIMS_SWIG_COMPAT_HEADER}\\"")
        endif()
    endif()
    # Windows needs nothing else: extensions must link pythonXY.lib and UseSWIG sets .pyd.
    if(WIN32)
        return()
    endif()
    # Turn the SWIG shared libraries into loadable Python extension modules on macOS/Linux.
    foreach(_target IN ITEMS py3dna py3riglogic)
        get_target_property(_libs ${_target} LINK_LIBRARIES)
        if(NOT _libs)
            set(_libs)
        endif()
        # Never link libpython into an extension: the interpreter provides the symbols and a
        # second (static) copy of the runtime would crash.
        list(REMOVE_ITEM _libs Python3::Python)
        list(APPEND _libs Python3::Module)
        set_property(TARGET ${_target} PROPERTY LINK_LIBRARIES "${_libs}")
        # Python only imports *.so here; versioned names (libX.so.13 / X.13.dylib) are invisible.
        set_property(TARGET ${_target} PROPERTY SUFFIX ".so")
        set_property(TARGET ${_target} PROPERTY VERSION)
        set_property(TARGET ${_target} PROPERTY SOVERSION)
        if(APPLE)
            target_link_options(${_target} PRIVATE
                "LINKER:-undefined,dynamic_lookup" "LINKER:-dead_strip_dylibs")
            set_property(TARGET ${_target} PROPERTY BUILD_RPATH "@loader_path")
            set_property(TARGET ${_target} PROPERTY INSTALL_RPATH "@loader_path")
        else()
            set_property(TARGET ${_target} PROPERTY BUILD_RPATH "$ORIGIN")
            set_property(TARGET ${_target} PROPERTY INSTALL_RPATH "$ORIGIN")
        endif()
    endforeach()
endfunction()
cmake_language(DEFER CALL _ai_sims_fixups)
"""

