def find_source(directory: Path) -> Source:
    cmakelists = directory / "CMakeLists.txt"
    if not cmakelists.is_file() or not (directory / "python" / "dna" / "DNA.i").is_file():
        raise BuildError(
            f"OpenRigLogic sources not found in {directory}.\n"
            "  clone them with: git clone -b 5.8 https://github.com/EpicGames/OpenRigLogic.git "
            f"{directory}"
        )
    match = re.search(r"set\(RL_VERSION\s+([0-9.]+)\)", cmakelists.read_text(encoding="utf-8"))
    if not match:
        raise BuildError(f"Could not read RL_VERSION from {cmakelists}")

    digest = hashlib.sha256()
    files = [cmakelists]
    for name in SOURCE_HASH_DIRS:
        files.extend(p for p in sorted((directory / name).rglob("*")) if p.is_file())
    for path in files:
        digest.update(path.relative_to(directory).as_posix().encode())
        digest.update(sha256(path).encode())
    return Source(directory=directory, version=match.group(1), tree_hash=digest.hexdigest())


def python_target() -> PythonTarget:
    major, minor = sys.version_info[:2]
    include_dir = Path(sysconfig.get_paths()["include"])
    if not (include_dir / "Python.h").is_file():
        raise BuildError(
            f"Python headers not found in {include_dir}. Use a full CPython build "
            "(uv-managed or python.org), not an embedded distribution."
        )
    library: Path | None = None
    if sys.platform == "win32":
        suffix = "t" if sysconfig.get_config_var("Py_GIL_DISABLED") else ""
        candidate = Path(sys.base_exec_prefix) / "libs" / f"python{major}{minor}{suffix}.lib"
        if not candidate.is_file():
            raise BuildError(f"Python import library not found: {candidate}")
        library = candidate
    else:
        libdir = sysconfig.get_config_var("LIBDIR")
        for name in (sysconfig.get_config_var("LDLIBRARY"), sysconfig.get_config_var("LIBRARY")):
            if libdir and name and (Path(libdir) / name).is_file():
                library = Path(libdir) / name
                break
    return PythonTarget(
        executable=Path(sys.executable),
        version=f"{major}.{minor}",
        full_version=platform.python_version(),
        include_dir=include_dir,
        library=library,
    )


def find_swig(explicit: Path | None) -> Swig:
    """Prefer the real binary from the `swig` wheel; its console launcher needs SWIG_LIB."""
    if explicit is None:
        try:
            import swig as swig_package  # type: ignore[import-not-found]
        except ImportError:
            swig_package = None
        if swig_package is not None:
            name = "swig.exe" if sys.platform == "win32" else "swig"
            binary = Path(swig_package.BIN_DIR) / name
            libraries = sorted(Path(swig_package.SWIG_SHARE_DIR).glob("*/swig.swg"))
            if binary.is_file() and libraries:
                return Swig(executable=binary, library_dir=libraries[-1].parent)
        explicit = which("swig")
    if explicit is None or not explicit.is_file():
        raise BuildError(
            "SWIG not found. Install the pipeline dev dependencies (`uv sync`; it includes the "
            "`swig` wheel), `brew install swig` on macOS, or pass --swig PATH."
        )
    library_dir = Path(capture([str(explicit), "-swiglib"]).strip().splitlines()[0])
    if not (library_dir / "swig.swg").is_file():
        raise BuildError(f"{explicit} reports SWIG library {library_dir} without swig.swg")
    return Swig(executable=explicit, library_dir=library_dir)


def cmake_version(cmake: Path) -> tuple[int, ...]:
    version = version_tuple(capture([str(cmake), "--version"]))
    if version[:2] < MIN_CMAKE:
        raise BuildError(
            f"{cmake} is CMake {'.'.join(map(str, version))}; "
            f"need >= {'.'.join(map(str, MIN_CMAKE))}"
        )
    return version


def pip_tool(module: str, attribute: str, name: str) -> Path | None:
    """Locate a tool shipped by a PyPI wheel (`cmake`, `ninja`) without requiring it."""
    try:
        package = __import__(module)
    except ImportError:
        return None
    directory = getattr(package, attribute, None)
    if directory is None:
        return None
    exe = Path(directory) / (f"{name}.exe" if sys.platform == "win32" else name)
    return exe if exe.is_file() else None


# ---------------------------------------------------------------------------- Windows


def _vswhere_installations() -> list[Path]:
    root = os.environ.get("PROGRAMFILES(X86)", r"C:\Program Files (x86)")
    vswhere = Path(root) / "Microsoft Visual Studio" / "Installer" / "vswhere.exe"
    found: list[Path] = []
    if vswhere.is_file():
        output = capture([
            str(vswhere), "-latest", "-products", "*", "-requires",
            "Microsoft.VisualStudio.Component.VC.Tools.x86.x64",
            "-property", "installationPath", "-utf8",
        ])  # fmt: skip
        found.extend(Path(line.strip()) for line in output.splitlines() if line.strip())
    for base in (os.environ.get("PROGRAMFILES", r"C:\Program Files"), root):
        found.extend(sorted(Path(base).glob("Microsoft Visual Studio/20*/*"), reverse=True))
    return [path for path in found if (path / "VC" / "Auxiliary" / "Build").is_dir()]


def _vcvars_arch() -> str:
    """vcvarsall argument for the interpreter's architecture on this host."""
    target = {"win-amd64": "x64", "win-arm64": "arm64", "win32": "x86"}.get(
        sysconfig.get_platform()
    )
    host = {"amd64": "x64", "x86_64": "x64", "arm64": "arm64", "x86": "x86"}.get(
        platform.machine().lower()
    )
    if target is None or host is None:
        raise BuildError(
            f"Unsupported Windows platform {sysconfig.get_platform()} on {platform.machine()}"
        )
    return target if host == target else f"{host}_{target}"


def _capture_vcvars_env(vcvarsall: Path, arch: str) -> dict[str, str]:
    # `cmd /u` writes the output of the built-in `set` as UTF-16, so non-ASCII paths survive.
    command = f'cmd.exe /d /u /s /c ""{vcvarsall}" {arch} >nul 2>&1 && set"'
    completed = subprocess.run(command, capture_output=True, check=False)
    if completed.returncode != 0:
        raise BuildError(f"{vcvarsall} {arch} failed with exit code {completed.returncode}")
    env: dict[str, str] = {}
    for line in completed.stdout.decode("utf-16-le").splitlines():
        key, sep, value = line.partition("=")
        if sep and key and not key.startswith("="):
            env[key] = value
    if not any(key.upper() == "VCTOOLSINSTALLDIR" for key in env):
        raise BuildError(f"{vcvarsall} {arch} did not set up an MSVC environment")
    return env


def windows_toolchain(cmake_override: Path | None, prefer_ninja: bool) -> Toolchain:
    installations = _vswhere_installations()
    if not installations:
        raise BuildError(
            "Visual Studio with the C++ workload (MSVC v143+) was not found. Install "
            "'Desktop development with C++' from the Visual Studio Installer."
        )
    vs = installations[0]
    arch = _vcvars_arch()
    env = _capture_vcvars_env(vs / "VC" / "Auxiliary" / "Build" / "vcvarsall.bat", arch)
    msvc = next((v for k, v in env.items() if k.upper() == "VCTOOLSVERSION"), "?")

    bundled = vs / "Common7" / "IDE" / "CommonExtensions" / "Microsoft" / "CMake"
    cmake = (
        cmake_override
        or which("cmake", env)
        or next((p for p in [bundled / "CMake" / "bin" / "cmake.exe"] if p.is_file()), None)
        or pip_tool("cmake", "CMAKE_BIN_DIR", "cmake")
    )
    if cmake is None:
        raise BuildError("CMake not found; install the 'C++ CMake tools for Windows' VS component")
    ninja = (
        which("ninja", env)
        or next((p for p in [bundled / "Ninja" / "ninja.exe"] if p.is_file()), None)
        or pip_tool("ninja", "BIN_DIR", "ninja")
    )
    version = cmake_version(cmake)
    if prefer_ninja and ninja is not None:
        return Toolchain(
            cmake=cmake,
            cmake_version=version,
            generator="Ninja",
            cmake_args=(f"-DCMAKE_MAKE_PROGRAM={ninja.as_posix()}",),
            env=env,
            description=f"MSVC {msvc} ({arch}) from {vs}, Ninja {ninja}",
        )
    vs_arch = {"x64": "x64", "arm64": "ARM64", "x86": "Win32"}[arch.split("_")[-1]]
    year = re.search(r"20\d\d", str(vs))
    generators = {"2022": "Visual Studio 17 2022", "2026": "Visual Studio 18 2026"}
    generator = generators.get(year.group(0) if year else "", "Visual Studio 17 2022")
    return Toolchain(
        cmake=cmake,
        cmake_version=version,
        generator=generator,
        generator_args=("-A", vs_arch),
        env=env,
        description=f"MSVC {msvc} via {generator} ({vs_arch})",
    )


# ---------------------------------------------------------------------------- macOS / Linux


def posix_toolchain(cmake_override: Path | None, prefer_ninja: bool) -> Toolchain:
    env = dict(os.environ)
    cmake_args: list[str] = []
    if sys.platform == "darwin":
        try:
            clang = capture(["xcrun", "--find", "clang++"]).strip()
        except (BuildError, FileNotFoundError) as error:
            raise BuildError(
                "Xcode command line tools are missing; run `xcode-select --install`."
            ) from error
        arch = platform.machine()  # the interpreter's arch (x86_64 under Rosetta)
        cmake_args.append(f"-DCMAKE_OSX_ARCHITECTURES={arch}")
        target = sysconfig.get_config_var("MACOSX_DEPLOYMENT_TARGET")
        if target:
            cmake_args.append(f"-DCMAKE_OSX_DEPLOYMENT_TARGET={target}")
        description = f"Apple clang ({clang}), {arch}, deployment target {target or 'default'}"
    else:
        description = f"system compiler on {platform.system()} {platform.machine()}"

    homebrew = [Path("/opt/homebrew/bin"), Path("/usr/local/bin")]
    cmake = (
        cmake_override
        or which("cmake")
        or next((p / "cmake" for p in homebrew if (p / "cmake").is_file()), None)
        or pip_tool("cmake", "CMAKE_BIN_DIR", "cmake")
    )
    if cmake is None:
        raise BuildError("CMake not found; `brew install cmake` (or `uv pip install cmake`).")
    ninja = (
        which("ninja")
        or next((p / "ninja" for p in homebrew if (p / "ninja").is_file()), None)
        or pip_tool("ninja", "BIN_DIR", "ninja")
    )
    if prefer_ninja and ninja is not None:
        generator = "Ninja"
        cmake_args.append(f"-DCMAKE_MAKE_PROGRAM={ninja}")
    else:
        generator = "Unix Makefiles"
    return Toolchain(
        cmake=cmake,
        cmake_version=cmake_version(cmake),
        generator=generator,
        cmake_args=tuple(cmake_args),
        env=env,
        description=description,
    )


# ---------------------------------------------------------------------------- build steps


def configure_args(
    source: Source, build_dir: Path, toolchain: Toolchain, python: PythonTarget, swig: Swig
) -> list[str]:
    args = [
        str(toolchain.cmake),
        "-S", source.directory.as_posix(),
        "-B", build_dir.as_posix(),
        "-G", toolchain.generator, *toolchain.generator_args,
        "-DCMAKE_BUILD_TYPE=Release",
        # Version.h / Defs.h are committed; regenerating them would dirty the clone.
        "-DREAD_ONLY_SOURCE_TREE=ON",
        # Tests and benchmarks fetch GoogleTest/Benchmark from the network.
        "-DRL_BUILD_TESTS=OFF",
        "-DRL_BUILD_BENCHMARKS=OFF",
        "-DRL_BUILD_EXAMPLES=OFF",
        f"-DRL_BUILD_PYTHON_WRAPPER={python.version}",
        f"-DPython3_EXECUTABLE={python.executable.as_posix()}",
        f"-DPython3_INCLUDE_DIR={python.include_dir.as_posix()}",
        f"-DSWIG_EXECUTABLE={swig.executable.as_posix()}",
        f"-DSWIG_DIR={swig.library_dir.as_posix()}",
        *toolchain.cmake_args,
    ]  # fmt: skip
    if python.library is not None:
        args.append(f"-DPython3_LIBRARY={python.library.as_posix()}")
    args.append(f"-DCMAKE_PROJECT_RigLogic4_INCLUDE={(build_dir / FIXUPS_FILE).as_posix()}")
    # Always passed (possibly empty) so a stale cache entry cannot keep a wrong setting.
    compat = (build_dir / SWIG_COMPAT_FILE).as_posix() if swig.needs_stringify_compat else ""
    args.append(f"-DAI_SIMS_SWIG_COMPAT_HEADER={compat}")
    return args


def cached_generator(build_dir: Path) -> str | None:
    cache = build_dir / "CMakeCache.txt"
    if not cache.is_file():
        return None
    match = re.search(r"^CMAKE_GENERATOR:INTERNAL=(.*)$", cache.read_text(errors="replace"), re.M)
    return match.group(1).strip() if match else None


def build_and_stage(
    source: Source, build_dir: Path, toolchain: Toolchain, python: PythonTarget, swig: Swig
) -> Path:
    if (generator := cached_generator(build_dir)) and generator != toolchain.generator:
        log(f"build dir was configured for {generator!r}; starting fresh")
        shutil.rmtree(build_dir)
    build_dir.mkdir(parents=True, exist_ok=True)
    (build_dir / FIXUPS_FILE).write_text(FIXUPS_CMAKE, encoding="utf-8")
    (build_dir / SWIG_COMPAT_FILE).write_text(SWIG_COMPAT_HEADER, encoding="utf-8")

    run(configure_args(source, build_dir, toolchain, python, swig), env=toolchain.env)
    jobs = str(os.cpu_count() or 4)
    run(
        [str(toolchain.cmake), "--build", build_dir.as_posix(), "--config", "Release",
         "--target", *TARGETS, "--parallel", jobs],
        env=toolchain.env,
    )  # fmt: skip

    staging = build_dir / "staging"
    if staging.exists():
        shutil.rmtree(staging)
    for component in COMPONENTS:
        run(
            [str(toolchain.cmake), "--install", build_dir.as_posix(), "--config", "Release",
             "--component", component, "--prefix", staging.as_posix()],
            env=toolchain.env,
        )  # fmt: skip
    return staging


def collect_outputs(staging: Path) -> list[Path]:
    """Proxies plus the native modules they import, found by reading the proxies."""
    outputs: list[Path] = []
    native_suffix = ".pyd" if sys.platform == "win32" else ".so"
    for proxy_name in PROXY_MODULES:
        proxies = sorted(staging.rglob(proxy_name))
        if len(proxies) != 1:
            raise BuildError(f"expected one {proxy_name} in {staging}, found {proxies}")
        proxy = proxies[0]
        # SWIG's moduleimport template imports the extension by its interface name.
        imported = set(re.findall(r"^\s*import (_py3\w+)\s*$", proxy.read_text("utf-8"), re.M))
        if len(imported) != 1:
            raise BuildError(f"cannot tell which native module {proxy} imports: {imported}")
        native = proxy.parent / f"{imported.pop()}{native_suffix}"
        if not native.is_file():
            found = sorted(p.name for p in proxy.parent.iterdir())
            raise BuildError(f"{proxy.name} imports {native.name}, not installed (have {found})")
        outputs.extend([proxy, native])
    return outputs


def fingerprint(source: Source, python: PythonTarget, tag: str) -> dict[str, object]:
    """What decides whether a rebuild is needed (known before any toolchain lookup)."""
    return {
        "script_version": SCRIPT_VERSION,
        "platform_tag": tag,
        "riglogic_version": source.version,
        "source_tree_sha256": source.tree_hash,
        "python_version": python.full_version,
        "python_base_prefix": sys.base_prefix,
    }


def build_info(
    stamp: dict[str, object], python: PythonTarget, swig: Swig, toolchain: Toolchain
) -> dict[str, object]:
    return {
        "fingerprint": stamp,
        "python_executable": str(python.executable),
        "toolchain": {
            "generator": toolchain.generator,
            "cmake": ".".join(map(str, toolchain.cmake_version)),
            "description": toolchain.description,
        },
        "swig": {
            "executable": str(swig.executable),
            "library": str(swig.library_dir),
            "stringify_compat": swig.needs_stringify_compat,
        },
    }


def is_up_to_date(destination: Path, stamp: dict[str, object]) -> bool:
    record_path = destination / BUILD_INFO_FILE
    if not record_path.is_file():
        return False
    try:
        record = json.loads(record_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return False
    if record.get("fingerprint") != stamp:
        return False
    files = record.get("files", {})
    return bool(files) and all(
        (destination / name).is_file() and sha256(destination / name) == digest
        for name, digest in files.items()
    )


@contextlib.contextmanager
def explain_locked_files(destination: Path) -> Iterator[None]:
    try:
        yield
    except PermissionError as error:
        raise BuildError(
            f"cannot replace {destination}: {error}. A Python process (pytest, a notebook, "
            "a running conversion) still has the bindings loaded; close it and retry."
        ) from error


def publish(
    outputs: list[Path], license_file: Path, destination: Path, info: dict[str, object]
) -> None:
    """Assemble the new vendor directory next to the old one, then swap them by renaming,
    so a failure (e.g. a loaded .pyd on Windows) leaves the previous build intact."""
    staging = destination.with_name(f"{destination.name}.new-{os.getpid()}")
    retired = destination.with_name(f"{destination.name}.old-{os.getpid()}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    for pattern in (f"{destination.name}.new-*", f"{destination.name}.old-*"):
        for leftover in destination.parent.glob(pattern):
            shutil.rmtree(leftover, ignore_errors=True)
    staging.mkdir()
    files: dict[str, str] = {}
    for path in [*outputs, license_file]:
        name = "LICENSE-OpenRigLogic.txt" if path == license_file else path.name
        shutil.copy2(path, staging / name)
        files[name] = sha256(staging / name)
    record = {**info, "built_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "files": files}
    (staging / BUILD_INFO_FILE).write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    try:
        with explain_locked_files(destination):
            if destination.exists():
                destination.rename(retired)
            staging.rename(destination)
    except BuildError:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    # Loaded modules may keep the old files busy on Windows; they go with the next build.
    shutil.rmtree(retired, ignore_errors=True)


def smoke_test(destination: Path, dna_file: Path | None) -> None:
    command = [sys.executable, "-I", "-c", SMOKE_TEST_CODE, str(destination)]
    if dna_file is not None:
        if not dna_file.is_file():
            raise BuildError(f"--smoke-dna file not found: {dna_file}")
        command.append(str(dna_file))
    log("smoke test in a fresh interpreter")
    completed = subprocess.run(command, check=False)
    if completed.returncode != 0:
        raise BuildError(f"smoke test failed (exit code {completed.returncode})")


# ---------------------------------------------------------------------------- CLI


def parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE, help="OpenRigLogic clone")
    parser.add_argument("--build-root", type=Path, default=DEFAULT_BUILD_ROOT)
    parser.add_argument("--vendor-root", type=Path, default=DEFAULT_VENDOR_ROOT)
    parser.add_argument("--cmake", type=Path, help="CMake executable to use")
    parser.add_argument("--swig", type=Path, help="SWIG executable to use")
    parser.add_argument(
        "--no-ninja", action="store_true", help="use the Visual Studio / Makefile generator"
    )
    parser.add_argument("--force", action="store_true", help="rebuild even when up to date")
    parser.add_argument(
        "--smoke-dna", type=Path, help="also load this DNA and evaluate the rig after building"
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        tag = platform_tag()
        source = find_source(args.source.resolve())
        python = python_target()
        stamp = fingerprint(source, python, tag)
        destination = args.vendor_root.resolve() / tag
        log(f"OpenRigLogic {source.version} for Python {python.full_version} [{tag}]")

        if not args.force and is_up_to_date(destination, stamp):
            log(f"up to date: {destination} (use --force to rebuild)")
        else:
            swig = find_swig(args.swig)
            prefer_ninja = not args.no_ninja
            if sys.platform == "win32":
                toolchain = windows_toolchain(args.cmake, prefer_ninja)
            else:
                toolchain = posix_toolchain(args.cmake, prefer_ninja)
            cmake = ".".join(map(str, toolchain.cmake_version))
            log(f"toolchain: {toolchain.description}; CMake {cmake}")
            log(f"swig: {swig.executable}")
            build_dir = args.build_root.resolve() / f"openriglogic-{tag}"
            staging = build_and_stage(source, build_dir, toolchain, python, swig)
            info = build_info(stamp, python, swig, toolchain)
            publish(collect_outputs(staging), source.directory / "LICENSE", destination, info)
            log(f"published to {destination}")
        smoke_test(destination, args.smoke_dna)
    except BuildError as error:
        print(f"[openriglogic] error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
