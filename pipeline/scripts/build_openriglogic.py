"""Build Epic's OpenRigLogic (DNA + RigLogic) Python bindings for the running interpreter.

Run from `pipeline/` with the interpreter that will import the bindings:

    uv run --no-sync python scripts/build_openriglogic.py [--force] [--smoke-dna FILE.dna]

What it does:

1. Finds the toolchain:
   - Windows: Visual Studio 2022+ (vswhere), MSVC environment from `vcvarsall.bat`, CMake and
     Ninja from that environment (VS bundles both). Falls back to the Visual Studio
     generator when Ninja is missing.
   - macOS: Xcode command line tools (clang), CMake and optionally Ninja from PATH,
     Homebrew or the `cmake`/`ninja` PyPI packages.
   - SWIG from the `swig` PyPI package (a pipeline dev dependency), `--swig` or PATH.
2. Configures OpenRigLogic (`pipeline/vendor-src/OpenRigLogic`) in Release with the Python
   wrapper enabled (`RL_BUILD_PYTHON_WRAPPER=<major.minor>`); tests, benchmarks and examples
   are off so nothing is downloaded. The source tree is never modified; a CMake fix-up
   written into the build directory (injected with `CMAKE_PROJECT_RigLogic4_INCLUDE`):
   - keeps `RigLogic.i` compiling with SWIG >= 4.4, which renamed the
     `SWIG_EXPAND_AND_QUOTE_STRING` macro it uses (feature-detected, forced include);
   - on macOS/Linux makes the modules proper extension modules: `.so` suffix, no libpython
     link (`-undefined dynamic_lookup` on macOS), `@loader_path`/`$ORIGIN` rpath.
3. Builds the `py3dna` and `py3riglogic` targets, installs their components into a staging
   directory and publishes the proxies, native modules and the MIT license to
   `pipeline/vendor/openriglogic/<platform_tag>/` with a `BUILD_INFO.json` fingerprint.
4. Imports both modules in a fresh, isolated interpreter (and optionally evaluates a DNA).

The script is idempotent: when the published fingerprint (sources, interpreter, options)
and file hashes match, it does nothing unless `--force` is given. Build trees live in
`pipeline/vendor-src/build/` and are reused incrementally.
"""

